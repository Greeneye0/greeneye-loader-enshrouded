# Writes src/exports.h: every export of the System32 DLLs the loader may be named as (dbgcore,
# umpdc, cfgmgr32), forwarded by name to that exact System32 file through
# \\.\GLOBALROOT\SystemRoot\System32 (an absolute path, so a forward never resolves back to the
# loader itself). Whatever name the loader is installed under, the functions callers import
# from that DLL reach the real one. Run from a VS x64 developer prompt (dumpbin).
import os, re, subprocess, sys

NAMES = ['dbgcore', 'umpdc', 'cfgmgr32']
# The forwarder path as it must appear inside a C string literal (every backslash doubled).
TARGET = r'\\\\.\\GLOBALROOT\\SystemRoot\\System32\\'
HERE = os.path.dirname(os.path.abspath(__file__))


def exports(name):
    out = subprocess.run(['dumpbin', '/nologo', '/exports', rf'C:\Windows\System32\{name}.dll'],
                         capture_output=True, text=True, check=True).stdout
    rows, started = [], False
    for line in out.splitlines():
        if re.match(r'\s+ordinal\s+hint\s+RVA\s+name', line):
            started = True
            continue
        if not started:
            continue
        if line.strip().startswith('Summary'):
            break
        m = re.match(r'\s+(\d+)\s+(?:[0-9A-F]+\s+)?(?:[0-9A-F]{8}\s+)?(\S+)', line)
        if m:
            rows.append(m.group(2))
    return rows


seen = {}
lines = ['// generated by tools/gen_exports.py - do not edit']
for name in NAMES:
    syms = exports(name)
    if any(s == '[NONAME]' for s in syms):
        sys.exit(f'{name} has ordinal-only exports; forward them by ordinal first')
    for s in syms:
        if s in seen:
            sys.exit(f'{s} is exported by both {seen[s]} and {name}')
        seen[s] = name
        lines.append(f'#pragma comment(linker, "/export:{s}={TARGET}{name}.{s}")')
    print(f'{name}: {len(syms)} exports')
with open(os.path.join(HERE, '..', 'src', 'exports.h'), 'w', newline='\r\n') as f:
    f.write('\n'.join(lines) + '\n')
print(f'total {len(seen)} forwarders')
